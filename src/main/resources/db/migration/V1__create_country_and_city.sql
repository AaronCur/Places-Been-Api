-- Baseline: the schema Hibernate (ddl-auto: update) created for the Country and City entities.
-- Existing databases are baselined at version 1 and skip this script; new databases are built from it.
-- Constraint names are Hibernate's generated ones on purpose, so baselined and new databases match
-- and later migrations can refer to them by name.

CREATE TABLE country
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL,
    flag VARCHAR(255),
    CONSTRAINT country_pkey PRIMARY KEY (id),
    CONSTRAINT ukllidyp77h6xkeokpbmoy710d4 UNIQUE (name)
);

CREATE TABLE city
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name       VARCHAR(255)     NOT NULL,
    latitude   DOUBLE PRECISION NOT NULL,
    longitude  DOUBLE PRECISION NOT NULL,
    country_id BIGINT           NOT NULL,
    CONSTRAINT city_pkey PRIMARY KEY (id),
    -- Blocks the same city name in two countries; to be dropped in a later migration (B1)
    CONSTRAINT ukqsstlki7ni5ovaariyy9u8y79 UNIQUE (name),
    CONSTRAINT uktot9ajsfwuxb6345nkdfk3qxj UNIQUE (name, country_id),
    CONSTRAINT fkrpd7j1p7yxr784adkx4pyepba FOREIGN KEY (country_id) REFERENCES country (id)
);
