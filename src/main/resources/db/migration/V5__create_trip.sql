-- One visit to a city. A city can have many trips; a null end_date means a day trip.
CREATE TABLE trip
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    city_id    BIGINT                   NOT NULL,
    start_date DATE                     NOT NULL,
    end_date   DATE,
    notes      VARCHAR(2000),
    -- Matches Hibernate's mapping of java.time.Instant
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT trip_pkey PRIMARY KEY (id),
    CONSTRAINT ck_trip_dates CHECK (end_date IS NULL OR end_date >= start_date),
    -- No ON DELETE: a city can't be deleted while it still has trips
    CONSTRAINT fk_trip_city FOREIGN KEY (city_id) REFERENCES city (id)
);

-- Postgres doesn't index foreign keys on its own; the delete cascade counts trips per city
CREATE INDEX idx_trip_city_id ON trip (city_id);
